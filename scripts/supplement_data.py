print(f"📊 总计: {len(models)} 条")
print(f"\n[按类别]")
for cat, cnt in category_count.most_common():
    print(f"  {cat}: {cnt}个")
print(f"\n[按公司 Top10]")
for org, cnt in org_count.most_common(10):
    print(f"  {org}: {cnt}个")

